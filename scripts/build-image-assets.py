#!/usr/bin/env python3
"""Create responsive image derivatives without modifying source photographs.

Requires cwebp (libwebp) and macOS sips. Run from any working directory.
The public manifest keeps original CMS URLs as keys so saved content can use
optimized display files without migrating or replacing its source assets.
"""
from pathlib import Path
import hashlib
import json
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'assets' / 'optimized'
WEBP = shutil.which('cwebp')
SIPS = shutil.which('sips')


def dimensions(path):
    out = subprocess.check_output([SIPS, '-g', 'pixelWidth', '-g', 'pixelHeight', str(path)], text=True)
    width = int(re.search(r'pixelWidth:\s*(\d+)', out).group(1))
    height = int(re.search(r'pixelHeight:\s*(\d+)', out).group(1))
    return width, height


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_derivative(source, width, ext, scratch, lossless=False, quality=86):
    temp = scratch / ('image-' + str(width) + '.' + ext)
    if ext == 'webp':
        args = [WEBP, '-quiet', '-m', '6', '-metadata', 'icc']
        args += ['-lossless', '-exact'] if lossless else ['-q', str(quality)]
        args += ['-resize', str(width), '0', str(source), '-o', str(temp)]
    else:
        args = [SIPS, '-s', 'format', 'png', '--resampleWidth', str(width), str(source), '--out', str(temp)]
    subprocess.run(args, check=True, stdout=subprocess.DEVNULL)
    content_hash = digest(temp)[:12]
    filename = source.stem + '-w' + str(width) + '-' + content_hash + '.' + ext
    target = OUTPUT / filename
    if not target.exists():
        shutil.copyfile(temp, target)
    return '/' + str(target.relative_to(ROOT)), temp.stat().st_size


def main():
    if not WEBP or not SIPS:
        raise SystemExit('Install cwebp and run on macOS with sips to rebuild image assets.')
    OUTPUT.mkdir(exist_ok=True)
    portrait_paths = sorted((ROOT / 'assets/staff/incoming-2026-10-24').glob('*.jpg'))
    sources = [(path, 'portrait') for path in portrait_paths]
    sources += [(ROOT / 'assets/photos' / name, kind) for name, kind in [
        ('wv-appalachian-mountains.jpg', 'hero'),
        ('appalachian-jubilee-music-2026.png', 'flyer'),
        ('appalachian-jubilee-2026.png', 'flyer'),
        ('matthews-family.jpg', 'photo'),
    ]]
    sources.append((ROOT / 'assets/logo-fairview-2026.png', 'logo'))
    manifest, report = {}, []
    original_hashes = {path: digest(path) for path, _ in sources}
    with tempfile.TemporaryDirectory(prefix='fairview-images-') as folder:
        scratch = Path(folder)
        for source, kind in sources:
            original_width, original_height = dimensions(source)
            widths = [256, 512] if kind == 'logo' else [320, 640, 1280, 1920] if kind == 'hero' else [320, 640, 1280]
            widths = sorted(set(min(width, original_width) for width in widths))
            variants = {}
            for width in widths:
                variants[width] = write_derivative(source, width, 'webp', scratch, lossless=kind == 'logo', quality=90 if kind == 'flyer' else 86)
            preferred = 256 if kind == 'logo' else 640 if kind == 'portrait' else 1280
            selected = min(widths, key=lambda width: abs(width - preferred))
            url, size = variants[selected]
            display_width, display_height = dimensions(ROOT / url.lstrip('/'))
            key = '/' + str(source.relative_to(ROOT))
            entry = {
                'src': url,
                'width': display_width,
                'height': display_height,
                'srcset': ', '.join(variants[width][0] + ' ' + str(width) + 'w' for width in widths),
                'thumbnail': variants[widths[0]][0],
            }
            if kind == 'logo':
                entry['favicon'] = write_derivative(source, 64, 'png', scratch)[0]
                entry['appleTouchIcon'] = write_derivative(source, 180, 'png', scratch)[0]
            manifest[key] = entry
            report.append({'source': key, 'originalBytes': source.stat().st_size, 'defaultBytes': size, 'defaultWidth': selected})
    for path, before in original_hashes.items():
        if digest(path) != before:
            raise RuntimeError('Original image changed: ' + str(path))
    (ROOT / 'assets/image-assets.js').write_text(
        '/* Generated by scripts/build-image-assets.py; original assets remain unchanged. */\n'
        + 'window.FBT_IMAGE_ASSETS = ' + json.dumps(manifest, indent=2) + ';\n')
    print(json.dumps({'images': len(manifest), 'originalBytes': sum(row['originalBytes'] for row in report),
                      'defaultBytes': sum(row['defaultBytes'] for row in report), 'files': report}, indent=2))


if __name__ == '__main__':
    main()
